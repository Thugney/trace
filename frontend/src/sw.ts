/// <reference lib="webworker" />
import { precacheAndRoute, cleanupOutdatedCaches } from 'workbox-precaching';
import { clientsClaim } from 'workbox-core';
import { registerRoute } from 'workbox-routing';
import { NetworkFirst, CacheFirst, StaleWhileRevalidate } from 'workbox-strategies';
import { ExpirationPlugin } from 'workbox-expiration';
import { CacheableResponsePlugin } from 'workbox-cacheable-response';

declare let self: ServiceWorkerGlobalScope;

// Take control immediately
self.skipWaiting();
clientsClaim();

// Clean old caches
cleanupOutdatedCaches();

// Precache all assets generated by the build
const manifest = self.__WB_MANIFEST || [];
precacheAndRoute(manifest);

// Cache API requests with NetworkFirst strategy
registerRoute(
  /^https?:\/\/.*\/api\/.*/i,
  new NetworkFirst({
    cacheName: 'api-cache',
    plugins: [
      new ExpirationPlugin({
        maxEntries: 100,
        maxAgeSeconds: 60 * 60 * 24 // 24 hours
      }),
      new CacheableResponsePlugin({
        statuses: [0, 200]
      })
    ],
    networkTimeoutSeconds: 10
  })
);

// Cache images with CacheFirst strategy
registerRoute(
  /\.(?:png|jpg|jpeg|svg|gif|webp)$/i,
  new CacheFirst({
    cacheName: 'images-cache',
    plugins: [
      new ExpirationPlugin({
        maxEntries: 60,
        maxAgeSeconds: 60 * 60 * 24 * 30 // 30 days
      })
    ]
  })
);

// Use StaleWhileRevalidate for CSS and JS (allows updates while serving cached)
registerRoute(
  /\.(?:css|js)$/i,
  new StaleWhileRevalidate({
    cacheName: 'static-resources',
    plugins: [
      new ExpirationPlugin({
        maxEntries: 60,
        maxAgeSeconds: 60 * 60 * 24 * 7 // 7 days
      }),
      new CacheableResponsePlugin({
        statuses: [0, 200]
      })
    ]
  })
);

// Cache fonts with CacheFirst strategy
registerRoute(
  /\.(?:woff|woff2|ttf|eot)$/i,
  new CacheFirst({
    cacheName: 'fonts-cache',
    plugins: [
      new ExpirationPlugin({
        maxEntries: 30,
        maxAgeSeconds: 60 * 60 * 24 * 365 // 1 year
      })
    ]
  })
);

// Push Notification Handlers
self.addEventListener('push', (event: PushEvent) => {
  console.log('[SW] Push received:', event);

  let data = {
    title: 'Family Learning Hub',
    body: 'You have a new notification',
    icon: '/pwa-192x192.png',
    badge: '/favicon-32x32.png',
    data: { url: '/' }
  };

  try {
    if (event.data) {
      const payload = event.data.json();
      data = {
        title: payload.title || data.title,
        body: payload.body || payload.message || data.body,
        icon: payload.icon || data.icon,
        badge: payload.badge || data.badge,
        data: payload.data || data.data
      };
    }
  } catch (e) {
    console.error('[SW] Error parsing push data:', e);
  }

  const options = {
    body: data.body,
    icon: resolveNotificationAsset(data.icon, '/pwa-192x192.png'),
    badge: resolveNotificationAsset(data.badge, '/favicon-32x32.png'),
    vibrate: [100, 50, 100],
    data: data.data,
    tag: getNotificationTag(data.data),
    requireInteraction: false
  } as NotificationOptions;

  event.waitUntil(
    Promise.all([
      self.registration.showNotification(data.title, options),
      // Notify all clients about the push so they can play sound
      self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then((clients) => {
        clients.forEach((client) => {
          client.postMessage({
            type: 'PUSH_RECEIVED',
            payload: {
              notificationType: (data.data as any)?.type || 'general',
              title: data.title,
              body: data.body
            }
          });
        });
      })
    ])
  );
});

self.addEventListener('notificationclick', (event: NotificationEvent) => {
  console.log('[SW] Notification clicked:', event);

  event.notification.close();

  const urlToOpen = (event.notification.data as any)?.url || '/';

  event.waitUntil(
    self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then((windowClients) => {
      // Check if there's already a window open
      for (const client of windowClients) {
        if (client.url.includes(self.location.origin) && 'focus' in client) {
          client.focus();
          if (urlToOpen !== '/') {
            (client as any).navigate(urlToOpen);
          }
          return;
        }
      }
      // If no window is open, open a new one
      if (self.clients.openWindow) {
        return self.clients.openWindow(urlToOpen);
      }
    })
  );
});

self.addEventListener('notificationclose', (event: NotificationEvent) => {
  console.log('[SW] Notification closed:', event);
});

function resolveNotificationAsset(asset: unknown, fallback: string): string {
  if (typeof asset !== 'string') {
    return fallback;
  }

  if (/^(\/|https?:\/\/)/i.test(asset)) {
    return asset;
  }

  return fallback;
}

function getNotificationTag(data: unknown): string | undefined {
  if (!data || typeof data !== 'object') {
    return undefined;
  }

  const payload = data as Record<string, unknown>;
  const explicitTag = typeof payload.notificationTag === 'string' ? payload.notificationTag : null;
  const taskId = payload.taskId;
  const type = typeof payload.type === 'string' ? payload.type : 'general';

  if (explicitTag) {
    return explicitTag;
  }

  if (typeof taskId === 'number' || typeof taskId === 'string') {
    return `${type}-${taskId}`;
  }

  return undefined;
}
